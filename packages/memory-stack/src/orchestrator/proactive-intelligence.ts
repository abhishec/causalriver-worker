const BUILT_IN_TEMPLATES: MonitorTemplate[] = [
  {
    name: 'threshold_breach',
    domain: 'any',
    severity: 'critical',
    description: 'Alert when a metric crosses a threshold',
    create: (params) => ({
      id: `threshold_${params.metric}_${Date.now()}`,
      name: `${params.metric} threshold breach`,
      domain: (params.domain as string) || 'unknown',
      check: (state) => {
        const value = getNestedValue(state, params.metric as string);
        if (typeof value !== 'number') return false;
        const threshold = params.threshold as number;
        const direction = params.direction as string || 'above';
        return direction === 'above' ? value > threshold : value < threshold;
      },
      severity: (params.severity as ProactiveMonitor['severity']) || 'critical',
      message: `${params.metric} has breached the ${params.direction || 'above'} threshold of ${params.threshold}`,
      enabled: true,
      metadata: params,
    }),
  },
  {
    name: 'stale_data',
    domain: 'any',
    severity: 'warning',
    description: 'Alert when data is too old',
    create: (params) => ({
      id: `stale_${params.source}_${Date.now()}`,
      name: `${params.source} data staleness`,
      domain: (params.domain as string) || 'unknown',
      check: (state) => {
        const lastUpdated = getNestedValue(state, `${params.source}_last_updated`);
        if (!lastUpdated) return true; // No data = stale
        const age = Date.now() - new Date(lastUpdated as string).getTime();
        const maxAgeMs = ((params.maxAgeHours as number) || 24) * 60 * 60 * 1000;
        return age > maxAgeMs;
      },
      severity: 'warning',
      message: `Data from ${params.source} is stale (older than ${params.maxAgeHours || 24} hours)`,
      enabled: true,
      metadata: params,
    }),
  },
  {
    name: 'cascade_forming',
    domain: 'any',
    severity: 'warning',
    description: 'Alert when multiple related domains show simultaneous changes',
    create: (params) => ({
      id: `cascade_${Date.now()}`,
      name: 'Cross-domain cascade forming',
      domain: 'cross-domain',
      check: (state) => {
        const domains = (params.watchDomains as string[]) || [];
        let changedCount = 0;
        for (const domain of domains) {
          const changed = getNestedValue(state, `${domain}_changed`);
          if (changed) changedCount++;
        }
        return changedCount >= ((params.minDomains as number) || 2);
      },
      severity: 'warning',
      message: 'Multiple domains showing simultaneous changes — potential cascade forming',
      enabled: true,
      metadata: params,
    }),
  },
];

