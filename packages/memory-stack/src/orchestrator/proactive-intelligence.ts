function generateRecommendations(monitor: ProactiveMonitor, _state: Record<string, unknown>): string[] {
  const recs: string[] = [];

  switch (monitor.severity) {
    case 'critical':
      recs.push(`Investigate ${monitor.domain} immediately`);
      recs.push('Check upstream dependencies for root cause');
      recs.push('Consider notifying stakeholders');
      break;
    case 'warning':
      recs.push(`Monitor ${monitor.domain} closely over the next 24-48 hours`);
      recs.push('Review recent changes that might have caused this');
      break;
    case 'info':
      recs.push(`Keep an eye on ${monitor.domain}`);
      break;
    case 'opportunity':
      recs.push(`Capitalize on the positive trend in ${monitor.domain}`);
      recs.push('Consider doubling down on what\'s working');
      break;
  }

  return recs;
}

function findRelatedDomains(domain: string): string[] {
  const relationships: Record<string, string[]> = {
    finance: ['revenue', 'cs', 'growth'],
    revenue: ['finance', 'marketing', 'cs'],
    cs: ['revenue', 'product', 'engineering'],
    marketing: ['revenue', 'growth', 'product'],
    engineering: ['product', 'cs'],
    product: ['engineering', 'cs', 'marketing'],
    growth: ['finance', 'marketing', 'revenue'],
    people: ['engineering', 'product'],
  };

  return relationships[domain] || [];
}
