/** Configuration for proactive intelligence */
export interface ProactiveIntelligenceConfig {
  /** Callback when an alert fires */
  onAlert?: (alert: ProactiveAlert) => Promise<void> | void;
  /** Minimum time between duplicate alerts (default: 4 hours) */
  alertCooldownMs?: number;
  /** Maximum alerts per scan cycle (default: 10) */
  maxAlertsPerScan?: number;
  /** Whether to track alert history (default: true) */
  trackHistory?: boolean;
  /** Verbose logging */
  verbose?: boolean;
}

/** A monitor that watches for specific conditions */
export interface ProactiveMonitor {
  /** Unique monitor ID */
  id: string;
  /** Monitor name */
  name: string;
  /** Domain being monitored */
  domain: string;
  /** Check function — returns true if alert should fire */
  check: (state: Record<string, unknown>) => boolean;
  /** Alert severity */
  severity: 'critical' | 'warning' | 'info' | 'opportunity';
  /** Message template (can use {{key}} placeholders) */
  message: string;
  /** Whether this monitor is active */
  enabled: boolean;
  /** Custom metadata */
  metadata?: Record<string, unknown>;
}

/** A proactive alert generated by monitoring */
export interface ProactiveAlert {
  /** Unique alert ID */
  id: string;
  /** Monitor that triggered this */
  monitorId: string;
  /** Monitor name */
  monitorName: string;
  /** Severity level */
  severity: 'critical' | 'warning' | 'info' | 'opportunity';
  /** Domain */
  domain: string;
  /** Alert message */
  message: string;
  /** When the alert was generated */
  timestamp: Date;
  /** Current state snapshot that triggered the alert */
  stateSnapshot: Record<string, unknown>;
  /** Whether the alert has been acknowledged */
  acknowledged: boolean;
  /** Whether the alert has been delivered to the user */
  delivered: boolean;
  /** Recommended actions */
  recommendations: string[];
  /** Related domains that might be affected */
  relatedDomains: string[];
}

/** Result of a monitoring scan cycle */
export interface ProactiveScanResult {
  /** Alerts generated in this scan */
  alerts: ProactiveAlert[];
  /** Monitors checked */
  monitorsChecked: number;
  /** Monitors that fired */
  monitorsFired: number;
  /** Monitors throttled (on cooldown) */
  monitorsThrottled: number;
  /** Scan duration in ms */
  durationMs: number;
  /** State health summary */
  healthSummary: {
    criticalAlerts: number;
    warningAlerts: number;
    infoAlerts: number;
    opportunities: number;
  };
  /** Natural language briefing */
  briefing: string;
}

/** Built-in monitor templates */
export interface MonitorTemplate {
  /** Template name */
  name: string;
  /** Domain */
  domain: string;
  /** Severity */
  severity: ProactiveMonitor['severity'];
  /** Description */
  description: string;
  /** Factory to create the monitor */
  create: (params: Record<string, unknown>) => ProactiveMonitor;
}

