/**
 * Proactive Intelligence — Push-Based Insight Delivery
 * ══════════════════════════════════════════════════════════
 *
 * Claude-level capability: Instead of waiting for questions, proactively
 * surfaces insights, warnings, and opportunities based on continuous
 * monitoring of the brain's knowledge state.
 *
 * Brain Analog: The Amygdala + Reticular Activating System — the brain's
 * alerting system that elevates important signals to conscious attention
 * before being asked.
 *
 * Features:
 * - Threshold-based alerting (metric crosses a boundary)
 * - Trend-based alerts (metric is on a concerning trajectory)
 * - Cascade early warning (cascade pattern starting to form)
 * - Knowledge decay alerts (stale information)
 * - Opportunity detection (positive signals that need attention)
 * - Alert deduplication and throttling
 * - Priority-based delivery (critical > warning > info)
 * - Configurable notification channels
 *
 * @example
 * ```typescript
 * const proactive = createProactiveIntelligence({
 *   onAlert: (alert) => sendSlackMessage(alert.channel, alert.message),
 * });
 *
 * // Register monitors
 * proactive.addMonitor({
 *   name: 'churn_spike',
 *   domain: 'cs',
 *   check: (state) => state.churn_rate > 0.05,
 *   severity: 'critical',
 *   message: 'Churn rate exceeded 5% threshold',
 * });
 *
 * // Run monitoring cycle
 * const alerts = await proactive.scan(currentState);
 * console.log(alerts);  // [{severity: 'critical', ...}]
 * ```
 *
 * @packageDocumentation
 */

