/**
 * Create a proactive intelligence engine for push-based insight delivery.
 *
 * Monitors the brain's knowledge state and proactively surfaces alerts,
 * warnings, and opportunities without waiting for user questions.
 */
export function createProactiveIntelligence(config: ProactiveIntelligenceConfig = {}) {
  const {
    onAlert,
    alertCooldownMs = 4 * 60 * 60 * 1000, // 4 hours
    maxAlertsPerScan = 10,
    trackHistory = true,
    verbose = false,
  } = config;

  const monitors: Map<string, ProactiveMonitor> = new Map();
  const alertHistory: ProactiveAlert[] = [];
  const lastFired: Map<string, number> = new Map(); // monitorId → last fire timestamp

  return {
    /**
     * Add a monitor to the proactive intelligence system.
     */
    addMonitor(monitor: ProactiveMonitor): void {
      monitors.set(monitor.id, monitor);
    },

    /**
     * Remove a monitor by ID.
     */
    removeMonitor(id: string): boolean {
      return monitors.delete(id);
    },

    /**
     * Create a monitor from a built-in template.
     */
    createFromTemplate(templateName: string, params: Record<string, unknown>): ProactiveMonitor | null {
      const template = BUILT_IN_TEMPLATES.find((t) => t.name === templateName);
      if (!template) return null;
      const monitor = template.create(params);
      monitors.set(monitor.id, monitor);
      return monitor;
    },

    /**
     * Run a monitoring scan cycle against the current state.
     */
    async scan(state: Record<string, unknown>): Promise<ProactiveScanResult> {
      const startTime = Date.now();
      const alerts: ProactiveAlert[] = [];
      let monitorsChecked = 0;
      let monitorsFired = 0;
      let monitorsThrottled = 0;

      for (const monitor of monitors.values()) {
        if (!monitor.enabled) continue;
        monitorsChecked++;

        // Check cooldown
        const lastFiredAt = lastFired.get(monitor.id) || 0;
        if (Date.now() - lastFiredAt < alertCooldownMs) {
          monitorsThrottled++;
          continue;
        }

        try {
          const shouldFire = monitor.check(state);
          if (shouldFire && alerts.length < maxAlertsPerScan) {
            const alert: ProactiveAlert = {
              id: generateAlertId(),
              monitorId: monitor.id,
              monitorName: monitor.name,
              severity: monitor.severity,
              domain: monitor.domain,
              message: monitor.message,
              timestamp: new Date(),
              stateSnapshot: { ...state },
              acknowledged: false,
              delivered: false,
              recommendations: generateRecommendations(monitor, state),
              relatedDomains: findRelatedDomains(monitor.domain),
            };

            alerts.push(alert);
            monitorsFired++;
            lastFired.set(monitor.id, Date.now());

            if (trackHistory) {
              alertHistory.push(alert);
            }

            // Deliver alert
            if (onAlert) {
              try {
                await onAlert(alert);
                alert.delivered = true;
              } catch (err) {
                // Non-critical: alert delivery failure is non-fatal — err instanceof Error ? err.message : String(err) logged for debugging
              }
            }
          }
        } catch (err) {
          // Non-critical: monitor check failure is non-fatal — err instanceof Error ? err.message : String(err) logged for debugging
        }
      }

      // Build briefing
      const healthSummary = {
        criticalAlerts: alerts.filter((a) => a.severity === 'critical').length,
        warningAlerts: alerts.filter((a) => a.severity === 'warning').length,
        infoAlerts: alerts.filter((a) => a.severity === 'info').length,
        opportunities: alerts.filter((a) => a.severity === 'opportunity').length,
      };

      const briefingParts: string[] = [];
      if (healthSummary.criticalAlerts > 0) {
        briefingParts.push(`🚨 ${healthSummary.criticalAlerts} critical alert(s) require immediate attention.`);
      }
      if (healthSummary.warningAlerts > 0) {
        briefingParts.push(`⚠️ ${healthSummary.warningAlerts} warning(s) detected.`);
      }
      if (healthSummary.opportunities > 0) {
        briefingParts.push(`🎯 ${healthSummary.opportunities} opportunity/ies identified.`);
      }
      if (alerts.length === 0) {
        briefingParts.push('✅ All clear — no alerts from this scan cycle.');
      }

      for (const alert of alerts) {
        briefingParts.push(`- [${alert.severity.toUpperCase()}] ${alert.domain}: ${alert.message}`);
      }

      return {
        alerts,
        monitorsChecked,
        monitorsFired,
        monitorsThrottled,
        durationMs: Date.now() - startTime,
        healthSummary,
        briefing: briefingParts.join('\n'),
      };
    },

    /**
     * Get alert history.
     */
    getHistory(limit?: number): ProactiveAlert[] {
      const sorted = [...alertHistory].sort((a, b) => b.timestamp.getTime() - a.timestamp.getTime());
      return limit ? sorted.slice(0, limit) : sorted;
    },

    /**
     * Acknowledge an alert.
     */
    acknowledgeAlert(alertId: string): boolean {
      const alert = alertHistory.find((a) => a.id === alertId);
      if (alert) {
        alert.acknowledged = true;
        return true;
      }
      return false;
    },

    /**
     * Restore the last-fired timestamp for a monitor (for throttling continuity across restarts).
     * Call this before scan() to prevent duplicate alerts after agent restart.
     */
    setLastFired(monitorId: string, timestamp: number): void {
      lastFired.set(monitorId, timestamp);
    },

    /**
     * Get all registered monitors.
     */
    getMonitors(): ProactiveMonitor[] {
      return Array.from(monitors.values());
    },

    /**
     * Get available templates.
     */
    getTemplates(): MonitorTemplate[] {
      return BUILT_IN_TEMPLATES;
    },

    /**
     * Generate a proactive context section for the LLM.
     */
    getContextSection(): string {
      const recent = alertHistory
        .filter((a) => Date.now() - a.timestamp.getTime() < 24 * 60 * 60 * 1000) // Last 24h
        .sort((a, b) => b.timestamp.getTime() - a.timestamp.getTime());

      if (recent.length === 0) return '';

      const lines: string[] = ['## Proactive Intelligence Alerts (Last 24h)'];
      const criticals = recent.filter((a) => a.severity === 'critical');
      const warnings = recent.filter((a) => a.severity === 'warning');
      const opps = recent.filter((a) => a.severity === 'opportunity');

      if (criticals.length > 0) {
        lines.push('', '### 🚨 Critical');
        for (const a of criticals.slice(0, 3)) {
          lines.push(`- **${a.domain}**: ${a.message}`);
          if (a.recommendations.length > 0) {
            lines.push(`  - Recommended: ${a.recommendations[0]}`);
          }
        }
      }

      if (warnings.length > 0) {
        lines.push('', '### ⚠️ Warnings');
        for (const a of warnings.slice(0, 3)) {
          lines.push(`- **${a.domain}**: ${a.message}`);
        }
      }

      if (opps.length > 0) {
        lines.push('', '### 🎯 Opportunities');
        for (const a of opps.slice(0, 3)) {
          lines.push(`- **${a.domain}**: ${a.message}`);
        }
      }

      return lines.join('\n');
    },

    /**
     * Get configuration.
     */
    getConfig(): ProactiveIntelligenceConfig {
      return { alertCooldownMs, maxAlertsPerScan, trackHistory, verbose };
    },
  };
}

